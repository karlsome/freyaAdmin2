function todayLot() {
  const d = new Date();
  return `${d.getFullYear()}${String(d.getMonth() + 1).padStart(2, "0")}${String(d.getDate()).padStart(2, "0")}`;
}

// Same values the Python script substitutes: the whole masterDB record + lotNumber + legacy aliases.
function buildPreviewData(record) {
  const data = {};
  Object.entries(record || {}).forEach(([k, v]) => {
    if (v === null || ["string", "number", "boolean"].includes(typeof v)) data[k] = v === null ? "" : String(v);
  });
  data.lotNumber = todayLot();
  data.productNumber = data["品番"] || "";
  data.qty = data["収容数"] || "";
  data.description = data["品名"] || "";
  data.banumber = data["背番号"] || "";
  return data;
}
