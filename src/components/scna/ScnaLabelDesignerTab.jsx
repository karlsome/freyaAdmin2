    if (type === "text") Object.assign(next, { text: content || "Text", size: el.size || 12, font: el.font || "Helvetica", align: el.align || "left" });
    else if (type === "barcode128" || type === "qr") next.bind = content;
    else next.strokeWidth = el.strokeWidth || 1;
