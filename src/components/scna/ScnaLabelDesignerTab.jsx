      setDirty(false);
      // Render the explorer thumbnail in the background (the sample item fills the fields when one is loaded).
      requestThumbnail?.({ layoutId: savedId, layout, data: sampleRecord ? buildPreviewData(sampleRecord) : null });
      onFlash?.({ type: "success", message: t("Layout saved", "レイアウトを保存しました") });
