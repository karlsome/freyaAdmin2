function defaultElement(type) {
  const base = { id: newId(), type, x: 10, y: 10 };
  switch (type) {
    case "text": return { ...base, w: 50, h: 8, text: "Text", size: 12, font: "Helvetica", align: "left" };
    case "barcode128": return { ...base, w: 60, h: 15, bind: "{品番}" };
    case "qr": return { ...base, w: 25, h: 25, bind: "{品番},{収容数},{lotNumber}" };
    case "line": return { ...base, w: 50, h: 0, strokeWidth: 1 };
    default: return { ...base, w: 40, h: 20, strokeWidth: 1 };
  }
}

// Deterministic fake bars so the preview looks like a barcode (real encoding happens in Python).
function barcodeBars(value, widthPx) {
  const bars = [];
  const seed = String(value || "0");
  let x = 0;
  let i = 0;
  while (x < widthPx) {
    const code = seed.charCodeAt(i % seed.length) + i * 7;
    const bw = 1 + (code % 3);
    if (i % 2 === 0) bars.push({ x, w: Math.min(bw, widthPx - x) });
    x += bw;
    i += 1;
  }
  return bars;
}

// Live QR preview from api.qrserver.com (preview only; the printer renders its own QR in Python).
const QR_API = "https://api.qrserver.com/v1/create-qr-code/?size=300x300&data=";
const qrImageCache = new Map(); // url -> HTMLImageElement (loaded)

function QrPreview({ content, side }) {
  const url = content ? `${QR_API}${encodeURIComponent(content)}` : "";
  const [loaded, setLoaded] = useState({ url: "", image: null });
  const img = qrImageCache.get(url) || (loaded.url === url ? loaded.image : null);

  useEffect(() => {
    if (!url || qrImageCache.has(url)) return undefined;
    let cancelled = false;
    // Debounce so typing in the content box doesn't fire a request per keystroke.
    const timer = window.setTimeout(() => {
      const image = new window.Image();
      image.crossOrigin = "anonymous";
      image.onload = () => {
        qrImageCache.set(url, image);
        if (!cancelled) setLoaded({ url, image });
      };
      image.src = url;
    }, 250);
    return () => { cancelled = true; window.clearTimeout(timer); };
  }, [url]);

  if (img) return <KonvaImage image={img} width={side} height={side} listening={false} />;

  // Placeholder while loading, offline, or when there is no content yet
  return (
    <>
      <Rect width={side} height={side} fill="#fff" stroke="#000" strokeWidth={1} listening={false} />
      <KonvaText x={0} y={side / 2 - 6} width={side} text="QR" align="center" fontSize={12} fill="#000" listening={false} />
    </>
  );
}

function ElementShape({ el, ppm, data }) {
  const w = el.w * ppm;
  const h = el.h * ppm;
  const show = (t) => (data ? fillTokens(t, data) : String(t || ""));

  const hit = <Rect width={Math.max(w, 4)} height={Math.max(h, 4)} fill="rgba(0,0,0,0.001)" />;

  if (el.type === "text") {
    const bold = String(el.font || "").includes("Bold");
    return (
      <>
        {hit}
        <KonvaText
          width={w}
          height={h}
          text={show(el.text)}
          fontSize={el.size * PT_TO_MM * ppm}
          fontFamily="Helvetica, Arial, sans-serif"
          fontStyle={bold ? "bold" : "normal"}
          align={el.align || "left"}
          fill="#000"
          wrap="none"
          listening={false}
        />
      </>
    );
  }
  if (el.type === "barcode128") {
    const value = show(el.bind);
    return (
      <>
        {hit}
        {barcodeBars(value, w).map((b, i) => (
          <Rect key={i} x={b.x} y={0} width={b.w} height={h} fill="#000" listening={false} />
        ))}
      </>
    );
  }
  if (el.type === "qr") {
    const side = Math.min(w, h);
    return (
      <>
        <Rect width={Math.max(w, 4)} height={Math.max(h, 4)} fill="rgba(0,0,0,0.001)" />
        <QrPreview content={show(el.bind || el.text)} side={side} />
      </>
    );
  }
  if (el.type === "line") {
    return (
      <>
        {hit}
        <Line points={[0, 0, w, h]} stroke="#000" strokeWidth={Math.max(1, (el.strokeWidth || 1) * PT_TO_MM * ppm)} listening={false} />
      </>
    );
  }
  return (
    <>
      {hit}
      <Rect width={w} height={h} stroke="#000" strokeWidth={Math.max(1, (el.strokeWidth || 1) * PT_TO_MM * ppm)} listening={false} />
    </>
  );
}

